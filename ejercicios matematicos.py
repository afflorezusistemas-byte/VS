# suma 
def suma(numero1,numero2):
   # definimos los parametros 
    
    suma = numero1 + numero2         #SUMA NUMERO 1 + NUMERO 2
    return suma                      # RETORNA SUMA

resultado = suma (1, 6)              #RESULTADO DE LA SUMA 
    
print(f"la suma es: {resultado}")     # IMPRIME EL RESULTADO 




